#!/usr/bin/env node
// Bakes a small real-elevation model of the Aconcagua massif for the scenic backdrop.
//
// Source: Mapzen/Tilezen "Terrain Tiles" (Terrarium encoding) on AWS Open Data,
// https://registry.opendata.aws/terrain-tiles/ — derived from SRTM and other open
// datasets; see assets/DEM-ATTRIBUTION.md. Output: assets/aconcagua-dem.bin
// (Uint16 little-endian metres, SIZE×SIZE, row 0 = north) and src/dem-meta.js.
//
// Usage: node prototype/web-3d/tools/bake-dem.mjs
import fs from 'node:fs';
import path from 'node:path';
import zlib from 'node:zlib';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const ZOOM = 11;
const SUMMIT = { lat: -32.6532, lon: -70.0109 };
const CROP_PX = 352;   // ~22.6 km at this latitude
const SIZE = 256;      // output grid

function decodePng(buf) {
  let off = 8;
  let width = 0; let height = 0; let colorType = 0; let bitDepth = 0;
  const idat = [];
  while (off < buf.length) {
    const len = buf.readUInt32BE(off);
    const type = buf.toString('ascii', off + 4, off + 8);
    const data = buf.subarray(off + 8, off + 8 + len);
    if (type === 'IHDR') { width = data.readUInt32BE(0); height = data.readUInt32BE(4); bitDepth = data[8]; colorType = data[9]; }
    else if (type === 'IDAT') idat.push(data);
    off += 12 + len;
  }
  if (bitDepth !== 8 || (colorType !== 2 && colorType !== 6)) throw new Error(`unsupported PNG (depth ${bitDepth}, type ${colorType})`);
  const bpp = colorType === 6 ? 4 : 3;
  const raw = zlib.inflateSync(Buffer.concat(idat));
  const stride = width * bpp;
  const out = Buffer.alloc(height * stride);
  for (let y = 0; y < height; y++) {
    const filter = raw[y * (stride + 1)];
    for (let x = 0; x < stride; x++) {
      const v = raw[y * (stride + 1) + 1 + x];
      const a = x >= bpp ? out[y * stride + x - bpp] : 0;
      const b = y > 0 ? out[(y - 1) * stride + x] : 0;
      const c = x >= bpp && y > 0 ? out[(y - 1) * stride + x - bpp] : 0;
      let r;
      if (filter === 0) r = v;
      else if (filter === 1) r = v + a;
      else if (filter === 2) r = v + b;
      else if (filter === 3) r = v + ((a + b) >> 1);
      else { const p = a + b - c; const pa = Math.abs(p - a); const pb = Math.abs(p - b); const pc = Math.abs(p - c); r = v + (pa <= pb && pa <= pc ? a : pb <= pc ? b : c); }
      out[y * stride + x] = r & 255;
    }
  }
  return { width, height, bpp, data: out };
}

const n = 2 ** ZOOM;
const fx = ((SUMMIT.lon + 180) / 360) * n;
const fy = ((1 - Math.asinh(Math.tan((SUMMIT.lat * Math.PI) / 180)) / Math.PI) / 2) * n;
const px = fx * 256;
const py = fy * 256;
// Centre the crop a little south-west of the summit: the approach looks at that side.
const x0 = Math.round(px - CROP_PX * 0.5 - 18);
const y0 = Math.round(py - CROP_PX * 0.5 + 22);
const tiles = new Map();
async function tile(tx, ty) {
  const key = `${tx}/${ty}`;
  if (!tiles.has(key)) {
    const res = await fetch(`https://s3.amazonaws.com/elevation-tiles-prod/terrarium/${ZOOM}/${tx}/${ty}.png`);
    if (!res.ok) throw new Error(`tile ${key}: HTTP ${res.status}`);
    tiles.set(key, decodePng(Buffer.from(await res.arrayBuffer())));
  }
  return tiles.get(key);
}
async function elevation(gx, gy) {
  const t = await tile(Math.floor(gx / 256), Math.floor(gy / 256));
  const i = ((gy % 256) * 256 + (gx % 256)) * t.bpp;
  return t.data[i] * 256 + t.data[i + 1] + t.data[i + 2] / 256 - 32768;
}
const crop = new Float32Array(CROP_PX * CROP_PX);
for (let y = 0; y < CROP_PX; y++) for (let x = 0; x < CROP_PX; x++) crop[y * CROP_PX + x] = await elevation(x0 + x, y0 + y);

const out = new Uint16Array(SIZE * SIZE);
let min = Infinity; let max = -Infinity; let maxAt = [0, 0];
for (let y = 0; y < SIZE; y++) {
  for (let x = 0; x < SIZE; x++) {
    const sx = (x / (SIZE - 1)) * (CROP_PX - 1);
    const sy = (y / (SIZE - 1)) * (CROP_PX - 1);
    const ix = Math.min(CROP_PX - 2, Math.floor(sx)); const iy = Math.min(CROP_PX - 2, Math.floor(sy));
    const tx = sx - ix; const ty = sy - iy;
    const v = crop[iy * CROP_PX + ix] * (1 - tx) * (1 - ty) + crop[iy * CROP_PX + ix + 1] * tx * (1 - ty)
      + crop[(iy + 1) * CROP_PX + ix] * (1 - tx) * ty + crop[(iy + 1) * CROP_PX + ix + 1] * tx * ty;
    out[y * SIZE + x] = Math.round(v);
    if (v < min) min = v;
    if (v > max) { max = v; maxAt = [x, y]; }
  }
}
const metresPerPx = (156543.03392 * Math.cos((SUMMIT.lat * Math.PI) / 180)) / n;
const extent = Math.round(metresPerPx * CROP_PX);
fs.writeFileSync(path.join(here, '..', 'assets', 'aconcagua-dem.bin'), Buffer.from(out.buffer));
fs.writeFileSync(path.join(here, '..', 'src', 'dem-meta.js'), `// GENERATED by tools/bake-dem.mjs — real elevation of the Aconcagua massif.
// Source: Terrain Tiles (Mapzen/Tilezen) on AWS Open Data. See assets/DEM-ATTRIBUTION.md.
export const DEM_META = ${JSON.stringify({ size: SIZE, extentMetres: extent, minMetres: Math.round(min), maxMetres: Math.round(max), summitCell: maxAt, zoom: ZOOM }, null, 2)};
`);
console.log({ SIZE, extent, min: Math.round(min), max: Math.round(max), maxAt, tiles: tiles.size });
